/** Normalize user input to a department code (e.g. "22", "2a", "971"). */
function normalizeCode(input) {
  const trimmed = input.trim().toUpperCase();
  if (!trimmed) return null;

  if (/^2[AB]$/.test(trimmed)) return trimmed;
  if (/^\d{1,3}$/.test(trimmed)) {
    const n = parseInt(trimmed, 10);
    if (n >= 1 && n <= 95) return String(n).padStart(2, "0");
    if (n >= 971 && n <= 976 && n !== 975) return String(n);
  }
  return trimmed in DEPARTMENT_BY_CODE ? trimmed : null;
}
